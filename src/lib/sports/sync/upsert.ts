// Used for F1 drivers, synced into the shared Players collection (an F1
// driver is structurally just an individual-sport player who has a team —
// see NormalizedPlayer in ../types for why this doesn't get its own
// collection).
export const upsertPlayer = async (
  sportId: number,
  normalized: NormalizedPlayer,
): Promise<number> => {
  const payload = await getPayloadClient()

  const teamId = normalized.teamExternalId
    ? await findTeamIdByExternalId(sportId, normalized.teamExternalId)
    : null

  const data = {
    name: normalized.name,
    sport: sportId,
    team: teamId,
    nationality: normalized.nationality,
    externalId: normalized.externalId,
  }

  const existing = await payload.find({
    collection: 'players',
    where: { and: [{ externalId: { equals: normalized.externalId } }, { sport: { equals: sportId } }] },
    limit: 1,
  })

  if (existing.docs[0]) {
    // Never touch slug on update — same reasoning as upsertCompetition above.
    const updated = await payload.update({ collection: 'players', id: existing.docs[0].id, data })
    return updated.id
  }

  const created = await payload.create({ collection: 'players', data: { ...data, slug: '' } })
  return created.id
}

